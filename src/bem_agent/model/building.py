"""Assemble a complete EnergyPlus model from a `BuildingSpec`."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from .constructions import ENVELOPE_PRESETS, Envelope, construction_objects
from .geometry import Geometry, geometry_objects
from .hvac import HVACSystem, hvac_objects
from .idf import IDFObject, missing_references, render_idf
from .loads import LOAD_PRESETS, InternalLoads, load_objects
from .schedules import SCHEDULE_PRESETS, OperatingHours, schedule_objects
from .weather import resolve_weather

ENERGYPLUS_VERSION = "25.1"


class BuildingSpec(BaseModel):
    """Everything needed to build one model. Presets can be named or given in full."""

    model_config = ConfigDict(validate_default=True)

    name: str = Field("Building", min_length=1, max_length=60, pattern=r"^[A-Za-z0-9_\- ]+$")
    location: str = Field("chicago", description="City key (see weather.CITIES) or .epw path")
    geometry: Geometry = Field(default_factory=Geometry)
    envelope: Envelope | str = "typical"
    loads: InternalLoads | str = "office"
    schedules: OperatingHours | str = "office"
    hvac: HVACSystem = HVACSystem.IDEAL_LOADS
    run_period: Literal["sizing_only", "annual"] = "sizing_only"

    @field_validator("envelope")
    @classmethod
    def _envelope(cls, v):
        return _preset(v, ENVELOPE_PRESETS, "envelope")

    @field_validator("loads")
    @classmethod
    def _loads(cls, v):
        return _preset(v, LOAD_PRESETS, "loads")

    @field_validator("schedules")
    @classmethod
    def _schedules(cls, v):
        return _preset(v, SCHEDULE_PRESETS, "schedules")


def _preset(value, presets: dict, label: str):
    if isinstance(value, str):
        if value not in presets:
            raise ValueError(f"unknown {label} preset {value!r}; choose from {sorted(presets)}")
        return presets[value].model_copy()
    return value


def simulation_objects(spec: BuildingSpec) -> list[IDFObject]:
    annual = spec.run_period == "annual"
    objects = [
        IDFObject("Version", [ENERGYPLUS_VERSION]),
        IDFObject(
            "SimulationControl",
            [
                "Yes",  # zone sizing
                "Yes",  # system sizing
                "Yes",  # plant sizing
                "Yes",  # run sizing periods
                "Yes" if annual else "No",  # run weather file period
                "No",
                1,
            ],
        ),
        IDFObject(
            "Building",
            [spec.name, spec.geometry.orientation_deg, "City", 0.04, 0.4, "FullExterior", 25, 6],
        ),
        IDFObject("Timestep", [4]),
        IDFObject("GlobalGeometryRules", ["UpperLeftCorner", "Counterclockwise", "Relative"]),
    ]
    if annual:
        objects.append(
            IDFObject(
                "RunPeriod",
                ["Annual", 1, 1, "", 12, 31, "", "", "Yes", "Yes", "No", "Yes", "Yes"],
            )
        )
    return objects


def output_objects() -> list[IDFObject]:
    return [
        IDFObject("Output:SQLite", ["SimpleAndTabular"]),
        IDFObject("Output:Table:SummaryReports", ["AllSummary"]),
        IDFObject("OutputControl:Table:Style", ["CommaAndHTML"]),
        IDFObject("Output:Variable", ["*", "Zone Mean Air Temperature", "Hourly"]),
        IDFObject("Output:Meter", ["Electricity:Facility", "Hourly"]),
        IDFObject("Output:Meter", ["NaturalGas:Facility", "Hourly"]),
        IDFObject("Output:Diagnostics", ["DisplayExtraWarnings"]),
    ]


def build_objects(spec: BuildingSpec, site_objects: list[IDFObject]) -> list[IDFObject]:
    """All model objects. `site_objects` = Site:Location + design days (see weather.py)."""
    geom_objs, zone_names = geometry_objects(spec.geometry)
    objects = [
        *simulation_objects(spec),
        *site_objects,
        *construction_objects(spec.envelope),
        *schedule_objects(spec.schedules),
        *geom_objs,
        *load_objects(spec.loads, zone_names),
        *hvac_objects(spec.hvac, zone_names),
        *output_objects(),
    ]
    problems = missing_references(objects)
    if problems:
        raise ValueError("Model has broken references:\n" + "\n".join(problems))
    return objects


def build_idf(
    spec: BuildingSpec,
    site_objects: list[IDFObject] | None = None,
    energyplus_dir: str | os.PathLike | None = None,
) -> str:
    """Render the model as IDF text. Site objects come from the weather .ddy if not given."""
    if site_objects is None:
        site_objects = resolve_weather(spec.location, energyplus_dir).site_objects()
    g = spec.geometry
    header = (
        f"Generated by bem_agent. {spec.name}: {g.num_floors} floor(s), "
        f"{g.total_floor_area_m2:.0f} m², WWR {g.window_to_wall_ratio:.0%}, "
        f"HVAC {spec.hvac.value}, location {spec.location}.\n"
        "Run with: energyplus --expandobjects (HVACTemplate objects)."
    )
    return render_idf(build_objects(spec, site_objects), header=header)


def write_idf(spec: BuildingSpec, path: str | os.PathLike, **kwargs) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_idf(spec, **kwargs))
    return path
