"""Generate src/bem_agent/model/_template_fields.py from an EnergyPlus IDD file.

Covers the HVACTemplate objects plus Sizing:Zone (written for ideal-loads models).

ExpandObjects (which turns HVACTemplate objects into full HVAC systems) does not apply
IDD defaults to blank or missing fields, so every template object must be written out
in full. This script records each template's field names and defaults.

Usage:
    python scripts/gen_template_fields.py path/to/Energy+.idd [version label] \\
        > src/bem_agent/model/_template_fields.py
"""

import json
import re
import sys

OBJECTS = [
    "HVACTemplate:Zone:IdealLoadsAirSystem",
    "HVACTemplate:Zone:PTHP",
    "HVACTemplate:Zone:VAV",
    "HVACTemplate:System:VAV",
    "HVACTemplate:Plant:ChilledWaterLoop",
    "HVACTemplate:Plant:Chiller",
    "HVACTemplate:Plant:HotWaterLoop",
    "HVACTemplate:Plant:Boiler",
    "Sizing:Zone",
]

FIELD = re.compile(r"^\s+[AN]\d+\s*[,;]\s*\\field\s+(.+?)\s*$", re.M)


def object_block(idd: str, name: str) -> str:
    start = re.search(rf"^{re.escape(name)},\s*$", idd, re.M).end()
    end = re.search(r"^[A-Za-z]", idd[start:], re.M)
    return idd[start : start + end.start()] if end else idd[start:]


def fields(block: str) -> list[tuple[str, str]]:
    out = []
    matches = list(FIELD.finditer(block))
    for i, m in enumerate(matches):
        body = block[m.end() : matches[i + 1].start() if i + 1 < len(matches) else len(block)]
        default = re.search(r"\\default\s+(.+)", body)
        out.append((m.group(1), default.group(1).strip() if default else ""))
    return out


def main(path: str) -> None:
    idd = open(path, encoding="latin-1").read()
    version = re.search(r"!IDD_Version\s+(\S+)", idd)
    label = sys.argv[2] if len(sys.argv) > 2 else (version.group(1) if version else "unknown")
    print('"""Field names and IDD defaults for HVACTemplate objects.')
    print()
    print("Generated by scripts/gen_template_fields.py from EnergyPlus IDD")
    print(f"{label}.")
    print("Do not edit by hand.")
    print('"""')
    print()
    print("TEMPLATE_FIELDS: dict[str, list[tuple[str, str]]] = {")
    for name in OBJECTS:
        print(f"    {json.dumps(name)}: [")
        for field, default in fields(object_block(idd, name)):
            print(f"        ({json.dumps(field)}, {json.dumps(default)}),")
        print("    ],")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
